-- Since we must build an FText ourselves, the runtime strings require the special symbols to be escaped, otherwise they won't print properly.
-- Example: In Lua we write \"Element\" for the colours but in the runtime it becomes "Element".
-- In order for the colours to not break, we must turn "Element" back into \"Element\" and also handle newlines.
local function EscapeStringCharacters(value)
    value = value:gsub("\\", "\\\\")
    value = value:gsub('"', '\\"')
    value = value:gsub("\n", "\\n")

    return value
end

-- UE4SS' implementation of FText has a major bug with this game where it expects the size of FTest properties to be 24 bytes, but the game only uses 16 bytes!
-- This caused UE4SS' function to write into adjacent memory and cause a memory corruption.
-- This would cause weird behaviour like giving the ability's targeting type an impossible value or it would cause a hard game crash.
-- With our own implementation we build the FText ourselves in order to circumvent this issue.
-- Let's hope that UE4SS fixes this issue at some point, since it has been a known problem for a few months now.
-- Our function gets the memory location of the ability's description property and we import our custom built FText into it.
-- Special thanks to SamTheMan for researching about this issue.
local function FTextCustom(skillObject, propertyName, newDescription, abilityNameID)
    local success, errorMessage = pcall(function()
        local reflection = skillObject:Reflection()

        if not reflection then
            Log("Failed to get reflection for skill object.")
            return
        end

        -- Find the skill's description reflection property.
        local property = reflection:GetProperty(propertyName)

        if not property then
            Log("Failed to find property for skill object.")
            return
        end

        -- Get the property's memory address.
        local pointer = property:ContainerPtrToValuePtr(skillObject)

        if not pointer then
            Log("Failed to find pointer address for property of skill object.")
            return
        end

        -- Build our own FText formatted string and import it directly into the corresponding description property.
        local customFText = 'INVTEXT("' .. EscapeStringCharacters(newDescription) .. '")'
        property:ImportText(customFText, pointer, 0, skillObject)
        Log("Imported text into FText property.")

        -- Add the new description to the version in the tracked abilities array.
        -- This will allow us to compare the descriptions and see if they are different, so we prevent unnecessary writing.
        -- Also check if abilityNameID is null because we use this function to modify the charge UI, which doesn't need a name ID.
        if abilityNameID then
            if propertyName == "Description" then
                trackedAbilities[abilityNameID].Description = newDescription
            elseif propertyName == "ShortDescription" then
                trackedAbilities[abilityNameID].ShortDescription = newDescription
            elseif propertyName == "name" then
                trackedAbilities[abilityNameID].Name = newDescription
            end
        end
    end)

    if not success then
        Log("Failed to set " .. propertyName .. ": " .. tostring(errorMessage))
    end
end

-- This function modifies the AP cost and description of abilities.
local function ModifyAbilityCostAndDescription(param, modifyAPCostOnly)
    -- Since we call this function from a hook that gives us a remote object and from upon loading a save with direct skill objects, we need to handle both possibilities.
    -- If it is a remote object then unwrap it, otherwise just use the param directly.
    local self = unwrap(param) or param

    -- Make sure it exists and is valid.
    if not self or not self:IsValid() then
        return
    end

    -- Check if the skill type is 1 and if it isn't, do nothing.
    -- 2 are gradient abilities and 3 are items, we ignore those.
    -- UNLESS it is Angel's eyes, we want to modify the ability's description and add charges on criticals but not make its cost customizable.
    if self.SkillType ~= 1 and self.NameID:ToString() ~= "AngelsEyes" then
        return
    end

    --Log("Skill: " .. tostring(self:GetFullName()))
    --Log("NameID: " .. tostring(self.NameID:ToString()))
    --Log("Name: " .. tostring(self.name:ToString()))
    --Log("Type: " .. tostring(self.SkillType))
    --Log("Description: " .. tostring(self.Description:ToString()))
    --Log("Short Description: " .. tostring(self.ShortDescription:ToString()))
    --Log("APCost: " .. tostring(self.APCost))
    --Log("Element Type: " .. tostring(self.BaseElementalType))
    --Log("Dynamic Element Enabled: " .. tostring(self.DynamicElementOverride))

    local abilityNameID = self.NameID:ToString()

    local abilityValues = GetAbilityOverrideValues(abilityNameID)

    if not abilityValues then
        return
    end

    -- Modifiy AP cost of this ability to our new value if it differs from our custom value.
    if self.APCost ~= abilityValues.APCost then
        self.APCost = abilityValues.APCost
        Log("Modified AP cost of ability: " .. tostring(abilityNameID))
    end

    -- Do nothing else if we only want to modify the AP cost.
    if modifyAPCostOnly then
        return
    end

    local abilityElement = ElementsHelper.GetAbilityElement(abilityNameID)

    if abilityElement and abilityElement == 0 and self.DynamicElementOverride ~= 1 then
        --self.BaseElementalType = dynamicWeaponElement
        self.DynamicElementOverride = 1
        Log("Modified dynamic element override of ability to weapon's element: " .. tostring(abilityNameID) .. " to value: " .. tostring(self.DynamicElementOverride))
    end

    -- Track this ability in our global array so we don't modify the descriptions unnecessarily if it never changes.
    if not trackedAbilities[abilityNameID] then
        -- Initialize the descriptions with null so that we will always receive and write the first description instance.
        -- Also track the skill object incase we load multiple saves during our game instance, so we know the descriptions need to be refreshed as well.
        trackedAbilities[abilityNameID] = {}
        trackedAbilities[abilityNameID].Description = nil
        trackedAbilities[abilityNameID].ShortDescription = nil
        trackedAbilities[abilityNameID].name = nil
        trackedAbilities[abilityNameID].skillObject = self
    end

    -- Set Powerful's targeting type to 0: "self", it is a pure self-buffing ability now.
    if abilityNameID == "Powerful_Gustave" and self.TargetingType ~= 0 then
        self.TargetingType = 0
        Log("Modified targeting type to 0: 'self' of ability " .. tostring(abilityNameID))
    end

    -- Build the name and short and long description strings for the ability.
    local assembledName = ""
    local assembledLongDescription = ""
    local assembledShortDescription = ""

    -- We're in battle, only display each character's respective ability name.
    if (IsValidChargeComponent() and overchargeCharacterTurn or selectedFreyInMenu) then
        if abilityValues.OverchargeName then
            assembledName = abilityValues.OverchargeName
        end

        if abilityValues.OverchargeLongDescription then
            assembledLongDescription = abilityValues.OverchargeLongDescription
        end

        if abilityValues.OverchargeShortDescription then
            assembledShortDescription = abilityValues.OverchargeShortDescription
        end
    -- Perfection descriptions.
    else
        if abilityValues.PerfectionName then
            assembledName = abilityValues.PerfectionName
        end

        if abilityValues.PerfectionLongDescription then
            assembledLongDescription = abilityValues.PerfectionLongDescription
        end

        if abilityValues.PerfectionShortDescription then
            assembledShortDescription = abilityValues.PerfectionShortDescription
        end
    end

    -- Incase this array field is null for some reason, do nothing.
    if not trackedAbilities[abilityNameID] then
        return
    end

    -- Set the skill's custom name.
    if assembledName ~= "" and trackedAbilities[abilityNameID].Name ~= assembledName or not trackedAbilities[abilityNameID].skillObject:IsValid() then
        FTextCustom(self, "name", assembledName, abilityNameID)
        Log("Modified name of ability: " .. tostring(abilityNameID))
    end

    -- Set the skill's long description which is shown in the character/skill tree menus and at the top left window during target selection in battle.
    -- Only do this if the description from our tracked abilities array is different.
    -- Due to the UE4SS memory corruption issue from handling FText properties, we can't read the description directly otherwise it could return garbage and crash the game.
    if assembledLongDescription ~= "" and trackedAbilities[abilityNameID].Description ~= assembledLongDescription or not trackedAbilities[abilityNameID].skillObject:IsValid() then
        FTextCustom(self, "Description", assembledLongDescription, abilityNameID)
        Log("Modified long description of ability: " .. tostring(abilityNameID))
    end

    -- This check handles dynamic short descriptions during battle.
    if overchargeCharacterTurn and IsValidChargeComponent() then
        -- Dynamically update Marking Shot's short description with the current stun chance we have based off the available amount of charges.
        if abilityNameID == "MarkingShot_Gustave" then
            assembledShortDescription = assembledShortDescription .. ("\nHas a " .. string.format("%g", (virtualCurrentCharges / virtualMaxCharges * markingShotMaxStunChance) * 100) .. " " .. abilityValues.OverchargeDynamicDescriptionPiece)
        -- Dynamically update the current amount of consumed charges for Ascending Assault.
        elseif abilityNameID == "AscendingAssault" then
            local consumedCharges = ascendingAssaultChargesConsumed + (ascendingAssaultCounter * ascendingAssaultAdditionalChargesConsumed)

            if consumedCharges > virtualMaxCharges then
                consumedCharges = virtualMaxCharges
            end

            assembledShortDescription = assembledShortDescription .. ("Consumes up to " .. consumedCharges .. " <keyword id=\"Gustave_Charges\">Charges</> " .. abilityValues.OverchargeDynamicDescriptionPiece)
        end
    end

    -- Set the skill's short description to what we just assembled on the fly.
    -- Only do this if the short description from our tracked abilities array is different.
    -- Due to the UE4SS memory corruption issue from handling FText properties, we can't read the description directly otherwise it could return garbage and crash the game.
    if assembledShortDescription ~= "" and trackedAbilities[abilityNameID].ShortDescription ~= assembledShortDescription or not trackedAbilities[abilityNameID].skillObject:IsValid() then
        FTextCustom(self, "ShortDescription", assembledShortDescription, abilityNameID)
        Log("Modified short description of ability: " .. tostring(abilityNameID))
    end

    -- Update the skill object of this array entry so we know if we loaded a new save.
    if not trackedAbilities[abilityNameID].skillObject:IsValid() then
        trackedAbilities[abilityNameID].skillObject = self
    end 

    -- This might no longer be needed since we circumvent UE4SS' FText bug that would corrupt this value.
    --self.TargetingType = targetingType
end

-- Retrieve all skill data objects.
local function GetAllSkillAssets()
    local skill_assets = FindAllOf("BP_DataAsset_Skill_C")

    if skill_assets then
        return skill_assets
    end

    return nil
end

-- Modify all abilities so that they show their correct descriptions and AP cost immediately.
local function ModifyAllDescriptionsAndCost()
    local skill_assets = GetAllSkillAssets()
    
    if skill_assets then
        -- Find all modifiable abilities and adjust their descriptions and AP cost for the skilltree or when entering a battle to avoid weird issues.
        for _, asset in pairs(skill_assets) do
            if asset and asset:IsValid() then
                ModifyAbilityCostAndDescription(asset, true)
            end
        end
        Log("Found all skill assets and modified their descriptions and AP cost.")
    else
        Log("Couldn't find skill assets and didn't modify anything.")
    end
end

