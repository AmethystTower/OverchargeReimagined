        if CustomFunctions.UsedChargeGeneratingAbility(usedLumiereAssault, usedFromFire, usedDefiantStrike, usedSpeedBurst, usedStrikeStorm, usedLightHolder, usedEndbringer, usedAngelsEyes) then
