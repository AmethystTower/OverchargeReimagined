-- This will try to register all of our charge component hooks everytime a battle starts.
local function TryRegisterChargeComponentHooks()
    -- Our hooks were already registered successfully, do nothing.
    if AreAllChargeComponentHooksRegistered() then
        Log("Charge component hooks in place.")
        return
    end

    Log("Trying to register charge component hooks...")

    -- This hook gets called when the game is constructing the Overcharge widget, responsible for drawing the current amount of charges, max charges and the arm image.
    if not constructPortraitHookRegistered then
        local ok = pcall(function()
            RegisterHook(hooking.OVERCHARGE_WIDGET_CONSTRUCT, function(param)
                -- This is the full widget object responsible for the UI.
                local self = unwrap(param)

                if self:IsValid() then
                    -- Cache the portrait text property for the charge counter for this fight so that we can call it from any of our hooks.
                    chargePortrait = self

                    -- Modify the portrait's charge counter.
                    -- Since we are using the game's native SetText() function which handles the writing into the property, using UE4SS' FText() function should be safe here.
                    if self.TextBlock_MaxValue:IsValid() then
                        Log("Modifying Overcharge's arm UI widget to " .. tostring(virtualMaxCharges) .. " max charges.")
                        self.TextBlock_MaxValue:SetText(FText("/" .. tostring(virtualMaxCharges)))
                    end
                end
            end)
        end)

        -- If it was successful, mark the hooks registrations as true.
        if ok then
            constructPortraitHookRegistered = true
            Log("Successfully registered OVERCHARGE_WIDGET_CONSTRUCT execution hook.")
        end
    end

    -- This hook gets called when the game thinks we reached the maximum charge amount and slightly moves the text and plays the "fully charged" sound.
    -- It messes up our custom charge counter in the UI once we reach the maximum charges so we have to fix it here.
    if not updateCurrentValueHookRegistered then
        local ok = pcall(function()
            RegisterHook(hooking.UPDATE_CURRENT_VALUE, function(param)
                if not IsValidChargeComponent() then
                    return
                end

                -- Fix the arm widget's charge counter so it displays the correct amount.
                if IsValidChargePortraitProperties() then
                    Log("Game thinks max charges were reached, update widget UI counter via UPDATE_CURRENT_VALUE.")
                    chargePortrait.TextBlock_CurrentValue:SetText(FText(tostring(virtualCurrentCharges)))
                end
            end)
        end)

        -- If it was successful, mark the hooks registrations as true.
        if ok then
            updateCurrentValueHookRegistered = true
            Log("Successfully registered UPDATE_CURRENT_VALUE execution hook.")
        end
    end

    -- This hook runs on our character when the battle begins.
    -- And it turns out this hook runs when he was eaten by an enemy and freed during battle as well.
    if not receiveBeginPlayHookRegistered then
        local ok = pcall(function()
            RegisterHook(hooking.RECEIVE_BEGIN_PLAY, function(param)
                local self = unwrap(param)

                -- Check if the charge component exists, if yes then cache it.
                if self:IsValid() then
                    virtualCurrentCharges = 0
                    consumedChargesFromAbility = 0
                    ascendingAssaultCounter = 0
                    firstTurn = true
                    overchargeCharacterTurn = false

                    Log("Internal Charge Counter: " .. tostring(virtualCurrentCharges))

                    -- Cache the charge component during the fight for easy access in our other hooks.
                    chargeComponent = self

                    -- Try registering the ability hooks for Overcharge and Shatter.
                    -- These hooks will fail if we don't have the needed character equipped for this battle.
                    -- Which means we will have to try and register these hooks every battle.
                    -- Also this needs to run AFTER saving our chargeComponent otherwise this will silently fail.
                    TryRegisterAbilityHooks()

                    -- This loads and initializes the skill voicelines, so we can use them in our Lua code during battle upon using specific skills.
                    LoadSoundAssets()

                    -- Reset all ability states incase some are left from our last fight.
                    ResetAbilityStates()

                    -- Also reset steeled strike incase it's true from our last fight.
                    usedSteeledStrike = false

                    -- Add a 2 second delay before applying the starting charges.
                    -- Otherwise we'd get an error and no charges due to calling this too early when the character is not fully initialized yet.
                    ExecuteWithDelay(2000, function()
                        -- This is another safety check to see if self still exists, since we are exceuting delayed code here.
                        if self:IsValid() then
                            Log("Adding " .. tostring(config.StartingCharges) .. " starting charges.")
                            self.ChangeCharge(config.StartingCharges)
                        end
                    end)
                end
            end)
        end)

        -- If it was successful, mark the hooks registrations as true.
        if ok then
            receiveBeginPlayHookRegistered = true
            Log("Successfully registered RECEIVE_BEGIN_PLAY execution hook.")
        end
    end

    -- This hook runs whenever our character gets his turn.
    if not onTurnStartHookRegistered then
        local ok = pcall(function()
            RegisterHook(hooking.ON_TURN_START, function(param)
                -- This is a safety incase we somehow ever lose the current charge component, get it when a new turn starts.
                -- Although this should NEVER happen.
                if not IsValidChargeComponent() then
                    local self = unwrap(param)

                    if self:IsValid() then
                        chargeComponent = self
                    else
                        return
                    end

                    Log("Charge component disappeared: Saved new valid charge component.")
                end

                -- Mark this as our turn.
                overchargeCharacterTurn = true

                -- We had used STEELED STRIKE last turn and didn't get hit, consume charges for increased damage now.
                if usedSteeledStrike then
                    steeledStrikeExecuted = true
                    CalculateAmountOfConsumedCharges("SteeledStrike", "Steeled Strike")
                end

                -- Check if this is our first turn, if yes then don't add the charges per turn yet.
                if IsValidChargeComponent() and not firstTurn then
                    Log("Adding " .. tostring(config.ChargesPerTurn) .. " charges per turn.")
                    chargeComponent.ChangeCharge(config.ChargesPerTurn)
                else
                    firstTurn = false
                end
            end)
        end)

        -- If it was successful, mark the hooks registrations as true.
        if ok then
            onTurnStartHookRegistered = true
            Log("Successfully registered ON_TURN_START execution hook.")
        end
    end

    -- This hook runs whenever the turn of our character ends.
    if not onTurnEndHookRegistered then
        local ok = pcall(function()
            RegisterHook(hooking.ON_TURN_END, function(param)
                -- This is a safety incase we somehow ever lose the current charge component, get it when a new turn starts.
                -- Although this should NEVER happen.
                if not IsValidChargeComponent() then
                    local self = unwrap(param)

                    if self:IsValid() then
                        chargeComponent = self
                    else
                        return
                    end

                    Log("Charge component disappeared: Saved new valid charge component.")
                end

                -- It is no longer our turn.
                overchargeCharacterTurn = false

                -- Reset all ability states.
                ResetAbilityStates()
            end)
        end)

        -- If it was successful, mark the hooks registrations as true.
        if ok then
            onTurnEndHookRegistered = true
            Log("Successfully registered ON_TURN_END execution hook.")
        end
    end

    -- This hook runs whenever someone dodges.
    if not dodgeSuccessfulHookRegistered then
        local ok = pcall(function()
            RegisterHook(hooking.DODGE_SUCCESSFUL, function(param, character, enemy)
                -- We have kept the default value of +1 charge per successful dodge, do nothing.
                if config.ChargesOnDodge == 1 then
                    return
                end

                if not IsValidChargeComponent() then
                    return
                end

                local dodgingCharacter = unwrap(character)

                -- The character that is dodging is not the one with Overcharge, skip.
                if not chargeComponent:IsCharacterOwner(dodgingCharacter) then
                    return
                end

                -- We have changed the value of the charges per dodge, add or remove them!
                -- We do -1 because the game already adds 1 charge by default.
                local calculatedCharges = config.ChargesOnDodge - 1

                chargeComponent.ChangeCharge(calculatedCharges)
            end)
        end)

        -- If it was successful, mark the hooks registrations as true.
        if ok then
            dodgeSuccessfulHookRegistered = true
            Log("Successfully registered DODGE_SUCCESSFUL execution hook.")
        end
    end

    -- This hook runs whenever someone parries.
    if not parrySuccessfulHookRegistered then
        local ok = pcall(function()
            RegisterHook(hooking.PARRY_SUCCESSFUL, function(param, character, enemy)
                -- We have kept the default value of +1 charge per successful parry, do nothing.
                if config.ChargesOnParry == 1 then
                    return
                end

                if not IsValidChargeComponent() then
                    return
                end

                local parryingCharacter = unwrap(character)

                -- The character that is parrying is not the one with Overcharge, skip.
                if not chargeComponent:IsCharacterOwner(parryingCharacter) then
                    return
                end

                -- We have changed the value of the charges per dodge, add or remove them!
                -- We do -1 because the game already adds 1 charge by default.
                local calculatedCharges = config.ChargesOnParry - 1

                chargeComponent.ChangeCharge(calculatedCharges)
            end)
        end)

        -- If it was successful, mark the hooks registrations as true.
        if ok then
            parrySuccessfulHookRegistered = true
            Log("Successfully registered PARRY_SUCCESSFUL execution hook.")
        end
    end

    -- This hook runs whenever someone gets broken/stunned.
    if not onBreakStunHookRegistered then
        local ok = pcall(function()
            RegisterHook(hooking.ON_BREAK_STUN, function(selfParam, sourceParam, reasonParam)
                if not IsValidChargeComponent() then
                    return
                end

                --local selfObject = unwrap(selfParam)
                local sourceCharacter = unwrap(sourceParam)

                -- Make sure the source character exists.
                if not sourceCharacter then
                    return
                end

                -- This is the reason for the break.
                local reason = unwrap(reasonParam)

                -- Get our actual breaking character from the parameter.
                local owner = sourceCharacter:GetOwner()

                -- IMPORTANT: Wrap this IsCharacterOwner() call into a pcall because sometimes the charge component can become a trivial object and make the call IsCharacterOwner() invalid.
                -- This can happen during the frame where we break and free our character after he was eaten by an enemy, which could cause the game to crash if not guarded properly.
                local success, isOwner = pcall(function()
                    return chargeComponent:IsCharacterOwner(owner)
                end)

                if not success then
                    Log("ON_BREAK_STUN: IsCharacterOwner failed: " .. tostring(isOwner))
                    return
                end

                -- Reason 1: Broken by an ability.
                if isOwner and reason == 1 then
                    -- Broken by Shatter.
                    if usedShatter then
                        -- We remove -10 from the calculated amount because Shatter is hardcoded to give 10 charges on a break.
                        Log("Player caused break using the ability Shatter, instantly refilling charges by " .. (shatterChargesPercentage * 100) .. "% of " .. virtualMaxCharges .. " total charges.")
                        chargeComponent.ChangeCharge(math.floor(virtualMaxCharges * shatterChargesPercentage) - 10)
                    -- Broken by Overcharge.
                    elseif usedOvercharge then
                        Log("Player caused break using the ability Overcharge, instantly refilling charges by " .. (overchargeChargesPercentage * 100) .. "% of " .. virtualMaxCharges .. " total charges.")
                        chargeComponent.ChangeCharge(math.floor(virtualMaxCharges * overchargeChargesPercentage))
                    -- Broken by Phantom Stars.
                    elseif usedPhantomStars then
                        Log("Player caused break using the ability Phantom Stars, instantly refilling charges by " .. (phantomStarsChargesPercentage * 100) .. "% of " .. virtualMaxCharges .. " total charges.")
                        chargeComponent.ChangeCharge(math.floor(virtualMaxCharges * phantomStarsChargesPercentage))
                    end
                end
            end)
        end)

        -- If it was successful, mark the hooks registrations as true.
        if ok then
            onBreakStunHookRegistered = true
            Log("Successfully registered ON_BREAK_STUN execution hook.")
        end
    end

    -- This hook runs whenever someone takes damage.
    if not onReceivedDamageHookRegistered then
        local ok = pcall(function()
            RegisterHook(hooking.ON_RECEIVED_DAMAGE, function(param, damageParam)
                if not IsValidChargeComponent() then
                    return
                end

                local damageObject = unwrap(damageParam)

                local statsComponentSource = damageObject.SourceCharacter
                local statsComponentTarget = damageObject.TargetCharacter

                local sourceOwner = statsComponentSource.GetOwner()
                local targetOwner = statsComponentTarget.GetOwner()

                local isSourceOwner = sourceOwner:IsValid() and chargeComponent:IsCharacterOwner(sourceOwner)
                local isTargetOwner = targetOwner:IsValid() and chargeComponent:IsCharacterOwner(targetOwner)

                -- We damaged ourselves, do nothing.
                if isSourceOwner and isTargetOwner then
                    return
                end

                -- Get the damage reason.
                damageReason = damageObject.DamageReason

                -- We dealt damage to an enemy!
                if isSourceOwner then
                    -- Critical hits: Add or remove charges based on critical hits, if enabled.
                    -- This is independent from Lumiere Assault and Strike Storm.
                    if damageObject.IsCriticalHit and config.ChargesOnCritical ~= 0 then
                        -- Check if the player enabled bonus charges from critical hits to affect free aim shots as well.
                        if damageReason ~= 3 or config.FreeAimAffectedByCriticals then
                            chargeComponent.ChangeCharge(config.ChargesOnCritical)
                            Log("Critical Damage: +" .. config.ChargesOnCritical .. " charges added.")
                        end
                    end

                    -- Damage Reason 1: Skill damage.
                    -- Add or remove charges for damaging enemies with abilities if it is NOT from Overcharge or Shatter, if enabled.
                    if damageReason == 1 then
                        chargeComponent.ChangeCharge(config.ChargesFromSkillDamage - 1)
                        Log("Skill Damage: +" .. config.ChargesFromSkillDamage .. " charges added.")

                        -- Monitor abilities that generate bonus charges on critical hits as their exclusive feature.
                        if damageObject.IsCriticalHit then
                            -- Light Holder.
                            if usedLightHolder then
                                chargeComponent.ChangeCharge(lightHolderChargesPerCritical)
                                Log("Light Holder Critical Damage: +" .. lightHolderChargesPerCritical .. " charges added.")

                            -- From Fire.
                            elseif usedFromFire then
                                chargeComponent.ChangeCharge(fromFireChargesPerCritical)
                                Log("From Fire Critical Damage: +" .. fromFireChargesPerCritical .. " charges added.")

                            -- Lumiere Assault.
                            -- Remove 1 from our value since the base game adds 1 per critical hit naturally already.
                            elseif usedLumiereAssault then
                                chargeComponent.ChangeCharge(lumiereAssaultChargesPerCritical - 1)
                                Log("Lumiere Assault Critical Damage: +" .. lumiereAssaultChargesPerCritical .. " charges added.")

                            -- Strike Storm.
                            -- Remove 2 from our value since the base game adds 2 per critical hit naturally already.
                            elseif usedStrikeStorm then
                                chargeComponent.ChangeCharge(strikeStormChargesPerCritical - 2)
                                Log("Strike Storm Critical Damage: +" .. strikeStormChargesPerCritical .. " charges added.")
                            end
                        end

                        -- Monitor Endbringer's hits when the target is stunned for bonus charges.
                        if usedEndbringer and statsComponentTarget.IsStun then
                            chargeComponent.ChangeCharge(endbringerChargesPerStunnedHit)
                            Log("Endbringer Stun Damage: +" .. endbringerChargesPerStunnedHit .. " charges added.")

                        -- The base game still adds charges from Overcharge's and Shatter's hit, so remove these hits.
                        elseif usedShatter or usedOvercharge then
                            chargeComponent.ChangeCharge((-1))

                        -- Add additional charges per hit from Angel's Eyes.
                        elseif usedAngelsEyes then
                            chargeComponent.ChangeCharge(angelsEyesAdditionalChargesPerHit)
                            Log("Angel's Eyes Damage: +" .. angelsEyesAdditionalChargesPerHit .. " charges added.")

                        -- Add additional charges per hit from Speed Burst.
                        elseif usedSpeedBurst then
                            chargeComponent.ChangeCharge(speedBurstChargesPerHit)
                            Log("Speed Burst Damage: +" .. speedBurstChargesPerHit .. " charges added.")
                        
                        -- Marking Shot has a chance to stun an enemy.
                        elseif usedMarkingShot then
                            -- Roll a number from 0.0 - 1.0 and compare it to the result when dividing current charges with max charges.
                            -- This means the chance depends on current charges, so 33 / 100 = 0.33, which is a 33% chance to stun in this example.
                            if math.random(1, 100) <= ( (consumedChargesFromAbility / virtualMaxCharges * markingShotMaxStunChance) * 100 ) then
                                -- Parameters: Character that gets broken and reason 1: Skill. This also resets break bar.
                                statsComponentTarget:PerformBreakStun(statsComponentSource, 1)
                                Log("Marking Shot has stunned the target.")
                            end

                            -- Fire extra hits at the target enemy, this is a SHOTGUN now!
                            -- TODO: This requires more testing to make sure this is stable, don't implement this yet.
                            --if not addingAdditionalPellets then
                            --    FirePellets(0, 8, temp_SkillScript, true)
                            --end

                        -- Blitz inflicts Stormcaller for 1 turn if enough charges are consumed.
                        elseif usedPurification and consumedChargesFromAbility == purificationChargesConsumed then
                            if temp_SkillScript and temp_SkillScript:IsValid() then
                                local appliedDebuff = {}
                                
                                -- Inflict Powerless on this enemy.
                                local powerlessClass = StaticFindObject("/Game/Gameplay/Buffs/StatsBuffs/BP_BattleBuff_Powerless.BP_BattleBuff_Powerless_C")
                                temp_SkillScript:ApplyBuff(powerlessClass, statsComponentTarget, 3, statsComponentSource, 4, appliedDebuff)
                                Log("Purification inflicted Powerless.")

                                temp_SkillScript = nil
                            end
                        end

                    -- Damage Reason 2: Buffs such as burn.
                    -- Add or remove charges for damaging enemies through buffs, if enabled.
                    elseif damageReason == 2 and config.ChargesOnBuffDamage ~= 0 then
                        chargeComponent.ChangeCharge(config.ChargesOnBuffDamage)
                        Log("Buff Damage: +" .. config.ChargesOnBuffDamage .. " charges added.")

                    -- Damage reason 3: Free aim shots.
                    -- Add/remove charges for shooting enemies, if enabled.
                    elseif damageReason == 3 and config.ChargesOnFreeAim ~= 0 then
                        chargeComponent.ChangeCharge(config.ChargesOnFreeAim)
                        Log("Free Aim Damage: +" .. config.ChargesOnFreeAim .. " charges added.")

                    -- Damage Reason 4: Basic attacks.
                    -- Add/remove charges for basic attacking enemies, if enabled.
                    elseif damageReason == 4 then
                        chargeComponent.ChangeCharge(config.ChargesOnBaseAttacks - 1)
                        Log("Base Attack Damage: +" .. config.ChargesOnBaseAttacks .. " charges added.")

                    -- Damage Reason 5 and 9: Normal counter attacks.
                    -- Add or remove charges for doing a normal or ranged counter attack, if enabled.
                    elseif damageReason == 5 or damageReason == 9 then
                        chargeComponent.ChangeCharge(config.ChargesOnCounterAttacks - 1)
                        Log("Counter Attack Damage: +" .. config.ChargesOnCounterAttacks .. " charges added.")

                    -- Damage reason 6: Lumina which is used by the Simoso "ethereal" sword ability for double light damage.
                    -- Add/remove charges for this effect, if enabled.
                    elseif damageReason == 6 and config.ChargesOnLuminaDamage ~= 0 then
                        chargeComponent.ChangeCharge(config.ChargesOnLuminaDamage)
                        Log("Lumina Damage: +" .. config.ChargesOnLuminaDamage .. " charges added.")

                    -- Damage Reason 8: Gradient counter attack.
                    -- Add or remove charges for doing a gradient counter attack, if enabled.
                    elseif damageReason == 8 then
                        chargeComponent.ChangeCharge(config.ChargesOnGradientCounter - 1)
                        Log("Gradient Counter Damage: +" .. config.ChargesOnGradientCounter .. " charges added.")

                    -- Damage Reason 11: Jump counter attack.
                    -- Add or remove charges for doing a jump counter attack, if enabled.
                    elseif damageReason == 11 then
                        chargeComponent.ChangeCharge(config.ChargesOnJumpCounter - 1)
                        Log("Jump Counter Damage: +" .. config.ChargesOnJumpCounter .. " charges added.")
                    end
                end

                -- We took damage from an enemy!
                if isTargetOwner then
                    -- Adds or removes charges when receiving a hit, if enabled.
                    -- Damage reason anything other than 2: Add or remove charges for anything that isn't buff damage (e.g. burn).
                    if damageReason ~= 2 and config.ChargesOnReceivedHit ~=0 then
                        chargeComponent.ChangeCharge(config.ChargesOnReceivedHit)
                        Log("Damage Taken: +" .. config.ChargesOnReceivedHit .. " charges added.")
                    end

                    -- Incase Steeled Strike is enabled, disable it now since we got hit and it was cancelled.
                    if usedSteeledStrike then
                        usedSteeledStrike = false
                    end
                end
            end)
        end)

        -- If it was successful, mark the hooks registrations as true.
        if ok then
            onReceivedDamageHookRegistered = true
            Log("Successfully registered ON_RECEIVED_DAMAGE execution hook.")
        end
    end

    -- This hook runs whenever charges get added/removed.
    if not changeChargeHookRegistered then
        local ok = pcall(function()
            RegisterHook(hooking.CHANGE_CHARGE, function(param, amount)
                -- Since we call ChangeCharge() in our hook, this prevents an infinite recursive call.
                if updatingNativeCharge then
                    return
                end

                if not IsValidChargeComponent() then
                    return
                end

                -- We already have the maximum amount of charges, so do nothing otherwise the player keeps hearing the "max charges" noise.
                -- Unless the added charge amount is negative, then in this case do NOT skip this instance.
                if(virtualCurrentCharges == virtualMaxCharges) and (read_int(amount) >= 0) then
                    return
                end

                -- Reset the max charges of the component to the original game value after OnExecuteSkill was executed.
                -- Since ChangeCarge() gets called basically everytime this is the perfect place to reset the max count cleanly.
                if restoreMaxCharges then
                    chargeComponent.MaxChargeCount = MAX_INGAME_CHARGES
                    restoreMaxCharges = false
                end

                -- Don't generate charges from the vanilla functionality of Powerful, since our version has been reworked to not do this anymore.
                if usedPowerful then
                    usedPowerful = false
                    return
                end

                -- The amount of charges that get added to our counter.
                -- Also includes the bonus charges from Lumiere Assault, Strike Storm and Shatter.
                Log("Added charges: "..tostring(read_int(amount)))

                -- Add the charges.
                virtualCurrentCharges = virtualCurrentCharges + read_int(amount)

                -- Make sure we don't go over our max limit.
                -- Also make sure our virtual charges never go below 0 as well.
                if(virtualCurrentCharges > virtualMaxCharges) then
                    virtualCurrentCharges = virtualMaxCharges
                elseif(virtualCurrentCharges < 0) then
                    virtualCurrentCharges = 0
                end

                Log("Internal Charge Counter: " .. tostring(virtualCurrentCharges))

                updatingNativeCharge = true
                
                -- Force game's internal charge counter back to 0 so that we can base it off the amount from our custom counter.
                chargeComponent.SetChargeCountInternal(0)

                -- Calculate the amount of in-game charges based off our internal counter multiplied by x.
                -- Ideally this will result in an increase in steps of 10.
                local charges = math.floor(virtualCurrentCharges * CHARGE_MULTIPLIER)

                -- This is a safety measure for the in-game counter just incase it somehow goes below 0 or above 10 charges.
                if(charges < 0) then
                    charges = 0
                elseif(charges > MAX_INGAME_CHARGES) then
                    charges = MAX_INGAME_CHARGES
                end

                -- Add the amount of in-game charges we calculated.
                -- This forces the current amount of charges to be used by the game for: gameplay, UI, animation selection and fx effect played on the arm.
                chargeComponent.ChangeCharge(charges)

                -- Update the existing charge portrait's current counter to the current charges from our custom own counter.
                if IsValidChargePortraitProperties() then
                    Log("Update widget UI counter via CHANGE_CHARGE.")
                    chargePortrait.TextBlock_CurrentValue:SetText(FText(tostring(virtualCurrentCharges)))
                end

                updatingNativeCharge = false
            end)
        end)

        -- If it was successful, mark the hooks registrations as true.
        if ok then
            changeChargeHookRegistered = true
            Log("Successfully registered CHANGE_CHARGE execution hook.")
        end
    end
end

-- This hook runs when loading a save.
RegisterHook(hooking.CLIENT_RESTART, function()
    if clientHookRegistered then
        return 
    end

    clientHookRegistered = true

    -- Try to load all charge component hooks upon loading a save because we prefer to have them as early as possible.
    -- This will fail if we don't have the overcharge character in our class but we want to have them registered as early as possible.
    TryRegisterChargeComponentHooks()

    -- Unfortunately we failed to register our charge component hooks.
    -- Register our function into the battle hook so it attempts it each time we start a battle.
    -- Although it seems like the hooks always register on the first battle so all of the checks and repeated attempts are just for safety incase it ever fails on first battle.
    if not AreAllChargeComponentHooksRegistered() then
        Log("Failed to register all charge component hooks due to missing overcharge character in party, hooking BATTLE_FULLY_LOADED to attempt to load them at start of each battle...")
        RegisterHook(hooking.BATTLE_FULLY_LOADED, TryRegisterChargeComponentHooks)
    end

    -- This hook runs when a battle started, so we can track it for our ability names hook.
    RegisterHook(hooking.BATTLE_STARTED, function(param)
        Log("BATTLE STARTED")
        selectedFreyInMenu = false
        loadingSystemComponent = nil
        updatedDynamicElement = false

        -- Cache the Overcharge skills we need for the sounds when a new battle begins.
        CacheOverchargeSkills()
    end)

    -- This hook runs when opening the character menu and selecting a specific character.
    RegisterHook(hooking.MENU_LOAD_CHARACTER_DATA, function(param, characterData)        
        local character = unwrap(characterData)

        if character:IsValid() then
            Log("CHARACTER NAME: " .. tostring(character.HardcodedNameID:ToString()))

            if character.HardcodedNameID:ToString() == "Frey" then
                selectedFreyInMenu = true
            else
                selectedFreyInMenu = false
            end
        end
    end)

    -- This hook runs when opening the skills menu in the character selection menu and update all of the skill values after changing names/description.
    RegisterHook(hooking.SKILLPANEL_LOAD_CHARACTER, function(param, characterData)
        local skillPanel = unwrap(param)

        if skillPanel:IsValid() then
            skillPanel:InitializeSlotsData()
        end
    end)

    -- This hook runs whenever the game is calculating the damage multiplier of an ability - usually when someone gets hit.
    -- We will also use this function to modify the elemental damage type of abilities since this is early enough for the game to accept the new value.
    RegisterHook(hooking.GET_ATTACK_MULTIPLIER, function(param)
        if not IsValidChargeComponent() then
            return
        end

        local modifier = unwrap(param)

        -- Return if the modifier somehow doesn't exist or the damage isn't caused by a skill.
        if not modifier or modifier.DamageReason ~= 1 then
            return
        end

        local owner = modifier.DamageSource:GetOwner()

        -- The damaging character somehow doesn't exist or is not the one with Overcharge, do nothing.
        if not owner or not chargeComponent:IsCharacterOwner(owner) then
            return
        end

        -- We used Overcharge, this will let us further increase its damage per charge if so desired.
        if usedOvercharge then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "UnleashCharge", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "UnleashCharge")

            -- Overcharge is full, further increase Overcharge's bonus damage!
            if fullChargeBonus then
                modifier.FinalDamageMultiplier = modifier.FinalDamageMultiplier + overchargeMaxChargesBonus
                Log("Full charge bonus: Increasing Overcharge's damage by another +" .. overchargeMaxChargesBonus .. " to a total of " .. modifier.FinalDamageMultiplier .. ".")
            end

        -- We used Shatter, it consumes ALL charges for increased damage!
        -- This is basically another version of Overcharge now, except it's slightly weaker but hits all enemies instead.
        elseif usedShatter then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "PerfectBreak_Gustave", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "PerfectBreak_Gustave")

            -- Overcharge is full, further increase Shatter's bonus damage!
            if fullChargeBonus then
                modifier.FinalDamageMultiplier = modifier.FinalDamageMultiplier + shatterMaxChargesBonus
                Log("Full charge bonus: Increasing Shatter's damage by another +" .. shatterMaxChargesBonus .. " to a total of " .. modifier.FinalDamageMultiplier .. ".")
            end

        -- We used Marking Shot, it consumes ALL charges for increased damage and a chance to instantly break!
        -- This is the third Overcharge-like ability now, except it's the weakest in damage but has a chance to stun an enemy immediately.
        elseif usedMarkingShot then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "MarkingShot_Gustave", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "MarkingShot_Gustave")

            -- Overcharge is full, further increase Marking Shot's bonus damage!
            if fullChargeBonus then
                modifier.FinalDamageMultiplier = modifier.FinalDamageMultiplier + markingShotMaxChargesBonus
                Log("Full charge bonus: Increasing Marking Shot's damage by another +" .. markingShotMaxChargesBonus .. " to a total of " .. modifier.FinalDamageMultiplier .. ".")
            end

        -- We used Lumiere Assault.
        elseif usedLumiereAssault then
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "Combo1_Gustave")

        -- We used Strike Storm.
        elseif usedStrikeStorm then
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "StrikeStorm_Gustave")

        -- We used From Fire.
        elseif usedFromFire then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "FromFire_Gustave", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "FromFire_Gustave")

            -- Heal our character based on the amount of charges we consumed.
            local result = {}

            -- Get the max health.
            modifier.DamageSource:GetMaxHP(result)

            -- Formula: Max health x heal per charge x amount of charges.
            local healAmount = (result.MaxHP * fromFireHealPerCharge) * consumedChargesFromAbility

            -- Heal based on amount of charges and max health.
            -- Params: Heal amount, character that healed us (ourselves in this case), play heal effect, self heal, debug string.
            -- This will damage us if we're inverted but since From Fire does this in the vanilla game we'll leave it like this.
            if healAmount > 0 then
                modifier.DamageSource.RecoverHP(healAmount, modifier.DamageSource, true, 1, "none")
            end

        -- We used the unused version of Radiant Strike.
        elseif usedRadiantStrike then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "RadiantStrike", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "RadiantStrike")

        -- We used the unused version of Light Holder which says it scales with health, get the max HP!
        -- I decided to not go for current health since that is a bit lame really, makes low-health builds not good with it then.
        -- This ability does not consume charges, it generates bonus charges on criticals instead.
        elseif usedLightHolder then
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "OldLightHolder")

            local result = {}
            modifier.DamageSource:GetMaxHP(result)

            -- Formula: Every x amount of max. health adds +x to the multiplier.
            local addedModifier = (result.MaxHP / lightHolderHealthChunkSize) * lightHolderDamagePerHealthChunk

            Log("FinalDamageMultiplier before: " .. tostring(modifier.FinalDamageMultiplier))

            modifier.FinalDamageMultiplier = modifier.FinalDamageMultiplier + addedModifier
            Log("Added +" .. addedModifier .. " to the damage multiplier based on " .. result.MaxHP .. " health for Light Holder.")

            Log("FinalDamageMultiplier after: " .. tostring(modifier.FinalDamageMultiplier))

        -- We used Steeled strike.
        elseif usedSteeledStrike then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "SteeledStrike", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "SteeledStrike")

        elseif usedEndbringer then
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "EndBringer")

        -- We used Berserk Slash
        elseif usedBerserkSlash then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "BerserkSlash", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "BerserkSlash")

        -- We used Defiant Strike
        elseif usedDefiantStrike then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "DefiantStrike", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "DefiantStrike")

        -- We used Blitz
        elseif usedBlitz then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "Blitz", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "Blitz")

        -- We used Follow Up
        elseif usedFollowUp then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "FollowUp", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "FollowUp")

        -- We used Ascending Assault
        elseif usedAscendingAssault then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "AscendingAssault", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "AscendingAssault")

        -- We used Speed Burst.
        elseif usedSpeedBurst then
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "SpeedBurst")

        -- We used Phantom Stars
        elseif usedPhantomStars then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "PhantomStars", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "PhantomStars")

        elseif usedParadigmShift then
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "ParadigmShift")

        -- We used Purification
        elseif usedPurification then
            modifier.FinalDamageMultiplier = IncreaseDamageMultiplierBasedOnCharges(modifier.FinalDamageMultiplier, "Purification", consumedChargesFromAbility)
            modifier.AttackElement = GetAbilityOverrideElement(modifier.AttackElement, "Purification")
        end
    end)

    -- This hook runs on any character's turn start.
    -- We will use it in order to grab the elemental damage type of our character's weapon for abilities that use it.
    RegisterHook(hooking.GENERIC_CHARACTER_TURN_START, function(param)
        if not IsValidChargeComponent() or updatedDynamicElement then
            return
        end

        local self = unwrap(param)

        if not self then
            return
        end
        
        -- Get the actual character from the parameter so we can check if this is the one who owns the overcharge component.
        local owner = self:GetOwner()

        -- Somehow owner doesn't exist or this character is not the one we need, do nothing.
        if not owner or not owner:IsValid() or not chargeComponent:IsCharacterOwner(owner) then
            return
        end

        -- Update the elemental damage type of the character's weapon.
        local newElement = self:GetBaseDamageType()

        if newElement ~= dynamicWeaponElement then
            dynamicWeaponElement = newElement
            updatedDynamicElement = true
            Log("Updated weapon elemental type: " .. tostring(dynamicWeaponElement))
        end
    end)

    -- This hook runs when we're in battle and open the ability menu.
    -- We will use this function to decide if an ability should be highlighted in orange because we have the optimal charge counts for them.
    RegisterHook(hooking.GET_COST, function(param, RemoteSkillState)
        if not IsValidChargeComponent() then
            return
        end

        -- It's a different character's turn, do nothing.
        if not overchargeCharacterTurn then
            return
        end

        local self = unwrap(param)

        if not self then
            return
        end

        local skillState = unwrap(RemoteSkillState)

        if not skillState then
            return
        end

        -- Check if the skill type is 1 and if it isn't, do nothing.
        -- 2 are gradient abilities and 3 are items, we ignore those.
        if self.SkillType ~= 1 then
            return
        end

        local abilityNameID = self.NameID:ToString()

        local abilityValues = GetAbilityOverrideValues(abilityNameID)

        if not abilityValues then
            return
        end

        -- Check if we are at max charges and the abilities are Overcharge or Shatter and highlight them.
        if virtualCurrentCharges == virtualMaxCharges and (abilityNameID == "UnleashCharge" or abilityNameID == "PerfectBreak_Gustave") then
            skillState:SetOvercharge(true, true)
            return
        end

        -- Check if we are using Acending Assault and have enough charges for it.
        -- This ability is a bit special since it can consume more charges the more it gets used.
        if abilityValues.ChargesConsumed and abilityNameID == "AscendingAssault" then
            local consumedCharges = abilityValues.ChargesConsumed + (ascendingAssaultCounter * ascendingAssaultAdditionalChargesConsumed)

            if consumedCharges > virtualMaxCharges then
                consumedCharges = virtualMaxCharges
            end

            if virtualCurrentCharges >= consumedCharges then
                skillState:SetOvercharge(true, true)
            end

            return
        end

        -- Check if we have all charges available that this ability could consume and hightlight it.
        if abilityValues.ChargesConsumed and virtualCurrentCharges >= abilityValues.ChargesConsumed then
            skillState:SetOvercharge(true, true)
            return
        end

        -- Check if we have 0 charges and this ability can generate bonus charges, highlight them.
        -- Except it's Endbringer, that ability only generates charges on stunned enemies.
        -- The game will automatically highlight it in orange for us when an enemy is stunned.
        if not abilityValues.ChargesConsumed and virtualCurrentCharges == 0 and abilityNameID ~= "EndBringer" then
            skillState:SetOvercharge(true, true)
        end
    end)

    -- This function runs when the game creates a new audio manager.
    -- We will use this in order to cache its live instance so that we can play our custom voicelines during battle.
    RegisterHook(hooking.AUDIO_MANAGER_INIT, function(param)
        if not IsValidChargeComponent() or IsValidAudioComponent() then
            return
        end

        local self = unwrap(param)

        if not self then
            return
        end

        -- Cache the newest instance of the audio manager.
        battleAudioManager = self
        Log("Cached battle audio manager.")
    end)

    -- This function gets executed whenever a skill triggers a voiceline.
    -- We will hijack this function and mute the original voiceline if we don't want it to play, while replacing it with our own custom ones.
    RegisterHook(hooking.PLAY_SKILL_BATTLE_LINE_INTERNAL, function(param, soundAsset)
        if not IsValidChargeComponent() then
            return
        end

        -- A different character plays this voiceline, do nothing.
        if not overchargeCharacterTurn then
            return
        end

        -- We used an ability that we want to keep its original voiceline for, or we are calling this function with a custom voiceline right now.
        -- In both cases do nothing.
        if KeepOriginalVoiceline() or voiceLinePlaying then
            return
        end

        -- This is the current audio manager instance.
        local self = unwrap(param)

        -- Do nothing if it doesn't exist for whatever reason.
        if not self then
            return
        end

        -- Silence the original voicelines of this ability.
        local interrupted = {}
        self:TryInterruptActiveSkillBattleLine(interrupted)
        Log("Silenced current battle line.")

        -- 50% chance to play no voiceline still since this function seems to trigger all the time, even if nothing is said.
        -- Otherwise we'd hear the voicelines with every cast.
        if math.random(1, 100) <= 50 then
            Log("50% RNG chance wasn't succcessful, not playing voiceline this time.")
            return
        end

        local voiceLine

        -- Check which ability we used and replace its original voiceline with a custom voiceline from our list.
        if usedOverload then
            voiceLine = voiceLinesList["counter"]
        elseif usedSteeledStrike then
            voiceLine = voiceLinesList["takethemdown"]
        elseif usedEndbringer then
            voiceLine = voiceLinesList["overcharge3"]
        elseif usedPhantomStars then
            voiceLine = voiceLinesList["takethemdown"]
        elseif usedBerserkSlash then
            voiceLine = voiceLinesList["breakcycle"]
        elseif usedDefiantStrike then
            voiceLine = voiceLinesList["battlewon"]
        elseif usedBlitz then
            voiceLine = voiceLinesList["buffteam"]
        elseif usedPurification then
            voiceLine = voiceLinesList["overcharge3"]
        elseif usedLightHolder then
            voiceLine = voiceLinesList["takethemdown"]
        elseif usedSabotage then
            voiceLine = voiceLinesList["battlewon"]
        elseif usedStriker then
            voiceLine = voiceLinesList["breakcycle"]
        elseif usedAngelsEyes then
            voiceLine = voiceLinesList["overcharge4"]
        else
            return
        end
        
        if voiceLine and voiceLine:IsValid() then
            voiceLinePlaying = true
            self:PlaySkillBattleLineInternal(voiceLine)
            Log("Replaced battle line with custom value.")
            voiceLinePlaying = false
        end
    end)

    -- This hook runs at the start of a battle, registering all objects used by objects such as skills, luminas and actors (e.g. enemies).
    RegisterHook(hooking.LOAD_DEPENDENCIES_FROM_OBJECT, function(param, object)
        if IsValidLoadingComponent() or loadingDependenciesGuard then
            return
        end

        local self = unwrap(param)

        if not self then
            return
        end

        -- Cache the system loading component for this fight.
        loadingSystemComponent = self
        Log("Cached system loading component.")

        -- Technically this guard isn't needed because we check if we cached the loading system component and then never enter this part of the code anymore.
        -- But you can never be safe enough.
        loadingDependenciesGuard = true

        -- TODO: This works and since we use the game's proper way of loading dependencies, it will cause no issues and the game will handle everything else regarding lifetime and whatnot.
        -- But if we don't have an overcharge component (character missing) then it would be nice to check if we really need to load them for the current fight.
        -- Again, this would be a very small but nice optimization to respect the game's loading patterns, but this is something for a future clean-up update.
        -- This causes no performance issues or much increased memory usage, it's just a few extra abilities that always get loaded so we can use their tied voicelines.
        -- Comparing the fact that using 3 characters with 6 skils each loads 18 of them in a battle, this isn't a big deal.
        if cachedSkills["UnleashCharge"] and cachedSkills["UnleashCharge"]:IsValid() then
            self:LoadDependenciesFromObject(cachedSkills["UnleashCharge"])
            Log("Loaded skill and sound dependencies for UnleashCharge skill.")
        end

        if cachedSkills["UnleashCharge"] and cachedSkills["MarkingShot_Gustave"]:IsValid() then
            self:LoadDependenciesFromObject(cachedSkills["MarkingShot_Gustave"])
            Log("Loaded skill and sound dependencies for MarkingShot_Gustave skill.")
        end

        if cachedSkills["UnleashCharge"] and cachedSkills["StrikeStorm_Gustave"]:IsValid() then
            self:LoadDependenciesFromObject(cachedSkills["StrikeStorm_Gustave"])
            Log("Loaded skill and sound dependencies for StrikeStorm_Gustave skill.")
        end

        if cachedSkills["UnleashCharge"] and cachedSkills["PerfectRecovery_Gustave"]:IsValid() then
            self:LoadDependenciesFromObject(cachedSkills["PerfectRecovery_Gustave"])
            Log("Loaded skill and sound dependencies for PerfectRecovery_Gustave skill.")
        end

        if cachedSkills["UnleashCharge"] and cachedSkills["Powerful_Gustave"]:IsValid() then
            self:LoadDependenciesFromObject(cachedSkills["Powerful_Gustave"])
            Log("Loaded skill and sound dependencies for Powerful_Gustave skill.")
        end

        loadingDependenciesGuard = false
    end)

    -- This hook modifies the AP cost and description of abilities.
    RegisterHook(hooking.GET_BASE_COST, ModifyAbilityCostAndDescriptionUnwrapper)

    -- For the first time we load into a save: Attempt to modify all descriptions and AP costs so that they are correct right away.
    -- We also cache the a few abilities related to voicelines that are tied to them for later use.
    ModifyAllDescriptionsAndCost()
end)
